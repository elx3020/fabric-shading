import { hash01 } from '../patterns/hash.ts';

/**
 * Wave-optics noise tiles (Yu et al. 2025, section 6.2 and supplemental section 5).
 *
 * Coherent light scattered by a fiber bundle forms a speckle pattern over outgoing
 * directions. Its intensity is N = (r^2 + i^2) / 2, where r and i are the real and
 * imaginary parts of a complex Gaussian field. N is exponentially distributed with mean 1,
 * so it multiplies a lobe without changing its average energy.
 *
 * The paper derives the field's spectrum from wave simulations of measured yarns, which we
 * don't have. Here the spectrum is a Gaussian whose width (the correlation length, in
 * texels) the editor exposes; it plays the role of fiber diameter: thinner fibers give
 * coarser angular speckle.
 *
 * Tiles are parameterized like a fiber lobe: u is the azimuth phi around the yarn axis
 * over [-pi, pi), v is the longitudinal angle theta over [-pi/2, pi/2]. Near the poles
 * (|theta| -> 90 deg, along the yarn) a phi interval spans a small cone, so rows are
 * blurred along u by 1 / cos(theta) as in the supplemental. Fields are generated by
 * periodic convolution, so every tile wraps seamlessly in both directions.
 *
 * Each RGB channel is one wavelength. All channels share the same white noise and differ
 * only in correlation length (speckle grains scale with wavelength), so a glint is white at
 * its center with colored fringes, like the real effect.
 */
export interface WaveNoiseParams {
  /** Tile edge in texels (power of two). */
  size: number;
  /** Independent instances per set; the shader picks one per yarn segment. */
  instances: number;
  /** Speckle correlation length in texels at the shortest wavelength, reflection set. */
  correlation: number;
  /** Correlation length for the high-order (light that entered the fibers) set; smoother. */
  highOrderCorrelation: number;
  /** Wavelengths in nm, one per RGB channel, shortest first. */
  wavelengths: readonly [number, number, number];
  seed: number;
}

export const defaultWaveNoiseParams: WaveNoiseParams = {
  size: 64,
  instances: 8,
  correlation: 1.5,
  highOrderCorrelation: 3.5,
  wavelengths: [450, 550, 650],
  seed: 1,
};

export interface WaveNoiseTiles {
  size: number;
  instances: number;
  /** 2 * instances layers: reflection set first, then the high-order set. */
  layers: number;
  /** RGBA8, layer-major (layer, row, column). A is 255. Decode with {@link decodeWaveNoise}. */
  data: Uint8Array;
}

/** Largest representable noise value; P(N > 8) = e^-8, about 0.03%. */
export const WAVE_NOISE_MAX = 8;

/** Square-root encoding spends the 8 bits where the exponential distribution has its mass. */
export function encodeWaveNoise(n: number): number {
  return Math.round(255 * Math.sqrt(Math.min(Math.max(n, 0), WAVE_NOISE_MAX) / WAVE_NOISE_MAX));
}

export function decodeWaveNoise(byte: number): number {
  const v = byte / 255;
  return WAVE_NOISE_MAX * v * v;
}

function gaussianWhite(count: number, seed: number): Float32Array {
  const out = new Float32Array(count);
  for (let i = 0; i < count; i += 2) {
    const u1 = Math.max(hash01(i, seed), 1e-12);
    const u2 = hash01(i + 1, seed);
    const r = Math.sqrt(-2 * Math.log(u1));
    out[i] = r * Math.cos(2 * Math.PI * u2);
    if (i + 1 < count) out[i + 1] = r * Math.sin(2 * Math.PI * u2);
  }
  return out;
}

function kernel(sigma: number): Float32Array {
  const radius = Math.max(1, Math.ceil(3 * sigma));
  const k = new Float32Array(2 * radius + 1);
  let sum = 0;
  for (let i = -radius; i <= radius; i++) {
    const w = Math.exp((-0.5 * i * i) / (sigma * sigma));
    k[i + radius] = w;
    sum += w;
  }
  for (let i = 0; i < k.length; i++) k[i]! /= sum;
  return k;
}

/** Periodic 1D convolution of one row (stride 1) or column (stride size). */
function convolve(src: Float32Array, dst: Float32Array, size: number, start: number, stride: number, k: Float32Array): void {
  const radius = (k.length - 1) / 2;
  for (let i = 0; i < size; i++) {
    let acc = 0;
    for (let j = -radius; j <= radius; j++) {
      const idx = (((i + j) % size) + size) % size;
      acc += k[j + radius]! * src[start + idx * stride]!;
    }
    dst[start + i * stride] = acc;
  }
}

/** Periodic separable Gaussian blur, then normalized to zero mean and unit variance. */
function smoothField(white: Float32Array, size: number, sigma: number): Float32Array {
  const k = kernel(sigma);
  const tmp = new Float32Array(white.length);
  const out = new Float32Array(white.length);
  for (let y = 0; y < size; y++) convolve(white, tmp, size, y * size, 1, k);
  for (let x = 0; x < size; x++) convolve(tmp, out, size, x, size, k);
  let mean = 0;
  for (const v of out) mean += v;
  mean /= out.length;
  let variance = 0;
  for (const v of out) variance += (v - mean) ** 2;
  const scale = 1 / Math.sqrt(variance / out.length);
  for (let i = 0; i < out.length; i++) out[i] = (out[i]! - mean) * scale;
  return out;
}

/** One speckle channel: intensity of the complex field, pole-filtered, mean exactly 1. */
function speckle(wr: Float32Array, wi: Float32Array, size: number, sigma: number): Float32Array {
  const r = smoothField(wr, size, sigma);
  const i = smoothField(wi, size, sigma);
  const n = new Float32Array(size * size);
  for (let p = 0; p < n.length; p++) n[p] = (r[p]! * r[p]! + i[p]! * i[p]!) / 2;

  const row = new Float32Array(size * size);
  for (let y = 0; y < size; y++) {
    const theta = ((y + 0.5) / size - 0.5) * Math.PI;
    const extra = sigma * (1 / Math.max(Math.cos(theta), 0.1) - 1);
    if (extra < 0.25) {
      for (let x = 0; x < size; x++) row[y * size + x] = n[y * size + x]!;
    } else {
      convolve(n, row, size, y * size, 1, kernel(extra));
    }
  }

  let mean = 0;
  for (const v of row) mean += v;
  mean /= row.length;
  for (let p = 0; p < row.length; p++) row[p]! /= mean;
  return row;
}

export function bakeWaveNoise(params: Partial<WaveNoiseParams> = {}): WaveNoiseTiles {
  const p = { ...defaultWaveNoiseParams, ...params };
  const { size, instances } = p;
  if (!Number.isInteger(Math.log2(size))) throw new RangeError(`noise tile size must be a power of two, got ${size}`);
  const layers = 2 * instances;
  const texels = size * size;
  const data = new Uint8Array(layers * texels * 4);
  const lambda0 = p.wavelengths[0];

  for (let layer = 0; layer < layers; layer++) {
    const highOrder = layer >= instances;
    const base = highOrder ? p.highOrderCorrelation : p.correlation;
    const layerSeed = Math.imul(p.seed, 7919) + layer * 2;
    const wr = gaussianWhite(texels, layerSeed);
    const wi = gaussianWhite(texels, layerSeed + 1);
    for (let c = 0; c < 3; c++) {
      const n = speckle(wr, wi, size, (base * p.wavelengths[c]!) / lambda0);
      for (let t = 0; t < texels; t++) data[(layer * texels + t) * 4 + c] = encodeWaveNoise(n[t]!);
    }
    for (let t = 0; t < texels; t++) data[(layer * texels + t) * 4 + 3] = 255;
  }
  return { size, instances, layers, data };
}
